"""Emit src/nh_ckpt_layout.c (pointer words, fields and copied lazy slots of struct nh_ctx) from a -g build.
usage: NH_SRC=<source> NH_ONAMES=<build>/include/onames.h \
       gdb -batch -ex 'set max-value-size unlimited' -ex 'source util/gen_ckpt_layout.py' <build>/libpufferhack.so
Regenerate whenever struct nh_ctx or a copied slot type changes; the emitted static asserts fail the build otherwise."""
import gdb, os, re
NUM_OBJECTS = int(re.search(r'#define\s+NUM_OBJECTS\s+(\d+)', open(os.environ['NH_ONAMES']).read()).group(1))
MAXSPELL = int(re.search(r'#define\s+MAXSPELL\s+(\d+)', open(os.environ['NH_ONAMES']).read()).group(1))
# copied lazy slots: slot -> (element type, count expression)
SLOTS = {3: ('struct nle_cmd_state', '1'), 20: ('coord', '1'), 25: ('struct nle_uinit_state', '1'),
         6: ('struct nle_apply_state', '1'), 12: ('struct nle_sp_lev_state', '1'), 13: ('lev_region', '1'),
         14: ('struct nle_display_state', '1'), 0: ('gbuf_state', '1'), 24: ('struct nle_shk_state', '1'),
         26: ('struct nle_do_name_state', '1'), 27: ('struct h2o_ctx', '1'), 28: ('struct launchplace_s', '1'),
         31: ('struct artifact', 'sizeof(artilist_baseline)/sizeof(artilist_baseline[0])'),
         38: ('struct nle_rndmonst_state', '1'), 39: ('struct nle_end_state', '1'),
         1: ('struct objclass', str(NUM_OBJECTS + 1)), 42: ('NhRect', '51'), 43: ('struct nle_dokick_state', '1'),
         45: ('struct nle_uhitm_state', '1'), 46: ('struct nle_do_wear_state', '1'), 9: ('struct nle_objnam_state', '1'),
         48: ('struct nle_pager_state', '1'), 37: ('int', str(MAXSPELL))}
def ptrs(t, base, out):
    t = t.strip_typedefs()
    if t.code == gdb.TYPE_CODE_PTR:
        out.append(base); return
    if t.code == gdb.TYPE_CODE_ARRAY:
        et = t.target(); n = t.sizeof // max(et.sizeof, 1); sub = []; ptrs(et, 0, sub)
        for i in range(n):
            out.extend(base + i * et.sizeof + o for o in sub)
        return
    if t.code in (gdb.TYPE_CODE_STRUCT, gdb.TYPE_CODE_UNION):
        seen = set()
        for f in t.fields():
            if f.bitpos is None or f.bitpos % 8: continue
            sub = []; ptrs(f.type, base + f.bitpos // 8, sub)
            for o in sub:
                if o not in seen: seen.add(o); out.append(o)
def site(slot):
    """file:line of the slot's use, so its type resolves in the right compile unit (and function, for local structs)"""
    pat = re.compile(r'nh_lazy\[ *%d *\]' % slot)
    for d in ('src', 'win/tty', 'win/rl'):
        for f in sorted(os.listdir(os.path.join(os.environ['NH_SRC'], d))):
            if not f.endswith('.c'): continue
            for i, line in enumerate(open(os.path.join(os.environ['NH_SRC'], d, f), errors='replace'), 1):
                if pat.search(line) and 'free(' not in line: return f'{d}/{f}', i
    raise RuntimeError(f'slot {slot} not found')
def lookup(name, slot):
    f, line = site(slot)
    sal = gdb.decode_line(f'{os.path.join(os.environ["NH_SRC"], f)}:{line}')[1][0]
    block = gdb.block_for_pc(sal.pc)
    return gdb.lookup_type(name, block)
ctx = gdb.lookup_type('struct nh_ctx')
P = []; ptrs(ctx, 0, P); P = sorted(set(P))
fields = [(f.bitpos // 8, f.type.sizeof, f.name) for f in ctx.fields()]
L = ['/* generated by util/gen_ckpt_layout.py from a -g build: do not edit */', '#include <stddef.h>', '#include "hack.h"',
     '#include "nh_ckpt.h"', '',
     '#ifdef NH_CKPT_BOOTSTRAP /* a -g build for this generator after struct nh_ctx changed */', '#define FIELD(f, o, s)', '#else',
     '#define FIELD(f, o, s) _Static_assert(offsetof(struct nh_ctx, f) == (o) && sizeof(((struct nh_ctx *) 0)->f) == (s), \\',
     '                                      "nh_ckpt_layout.c is stale: rerun util/gen_ckpt_layout.py")', '#endif']
L += [f'FIELD({n}, {o}, {sz});' for o, sz, n in [(f.bitpos // 8, f.type.sizeof, f.name) for f in ctx.fields()]]
L += ['',
     f'const unsigned nh_ckpt_ctx_size = {ctx.sizeof};', f'const unsigned nh_ckpt_nptr = {len(P)};',
     'const unsigned nh_ckpt_ptr[] = {']
L += ['    ' + ', '.join(map(str, P[i:i + 16])) + ',' for i in range(0, len(P), 16)]
L += ['};', f'const unsigned nh_ckpt_nfield = {len(fields)};', 'const struct nh_ckpt_field nh_ckpt_field[] = {']
L += [f'    {{{o}, {s}, "{n}"}},' for o, s, n in fields]
L += ['};']
slot_rows = []; slot_ptrs = []
for s, (ty, cnt) in sorted(SLOTS.items()):
    t = lookup(ty, s); n = int(gdb.parse_and_eval(cnt)) if 'artilist' not in cnt else int(gdb.parse_and_eval('sizeof(artilist_baseline)')) // t.sizeof; sub = []; ptrs(t, 0, sub)
    first = len(slot_ptrs)
    for i in range(n): slot_ptrs.extend(i * t.sizeof + o for o in sub)
    slot_rows.append((s, t.sizeof * n, first, len(slot_ptrs) - first, ty))
L += [f'const unsigned nh_ckpt_nslot = {len(slot_rows)};', 'const struct nh_ckpt_slot nh_ckpt_slot[] = {']
L += [f'    {{{s}, {b}, {f}, {k}}}, /* {ty} */' for s, b, f, k, ty in slot_rows]
L += ['};', 'const unsigned nh_ckpt_slot_ptr[] = {']
L += ['    ' + ', '.join(map(str, slot_ptrs[i:i + 16])) + ',' for i in range(0, len(slot_ptrs), 16)] or ['    0,']
L += ['};', '']
open(os.path.join(os.environ['NH_SRC'], 'src/nh_ckpt_layout.c'), 'w').write('\n'.join(L))
print('nh_ckpt_layout.c:', len(P), 'pointer words,', len(fields), 'fields,', len(slot_rows), 'slots,', len(slot_ptrs), 'slot pointer words')
